// Helper to generate realistic candlestick data with technical indicators
function generateCandlesticks(basePrice: number, volatility: number = 0.015, count: number = 30) {
  const points = [];
  let currentPrice = basePrice * 0.95;
  const now = new Date();

  for (let i = count; i >= 0; i--) {
    const d = new Date(now.getTime() - i * 24 * 60 * 60 * 1000);
    const dateStr = d.toLocaleDateString('en-US', { month: 'short', day: 'numeric' });
    
    const delta = (Math.random() - 0.48) * volatility * currentPrice;
    const open = currentPrice;
    const close = Math.max(open + delta, 1);
    const high = Math.max(open, close) + Math.random() * volatility * currentPrice * 0.5;
    const low = Math.min(open, close) - Math.random() * volatility * currentPrice * 0.5;
    const volume = Math.floor(Math.random() * 5000000 + 1000000);

    currentPrice = close;
    points.push({
      time: dateStr,
      open: Number(open.toFixed(2)),
      high: Number(high.toFixed(2)),
      low: Number(low.toFixed(2)),
      close: Number(close.toFixed(2)),
      volume,
    });
  }

  // Calculate Simple Moving Averages and RSI
  for (let idx = 0; idx < points.length; idx++) {
    const slice20 = points.slice(Math.max(0, idx - 19), idx + 1);
    const sum20 = slice20.reduce((acc, p) => acc + p.close, 0);
    points[idx].sma20 = Number((sum20 / slice20.length).toFixed(2));

    const slice50 = points.slice(Math.max(0, idx - 49), idx + 1);
    const sum50 = slice50.reduce((acc, p) => acc + p.close, 0);
    points[idx].sma50 = Number((sum50 / slice50.length).toFixed(2));

    // Simulated RSI between 30 and 75
    const rsiVal = 50 + Math.sin(idx * 0.5) * 20 + (Math.random() - 0.5) * 8;
    points[idx].rsi = Number(Math.min( Math.max(rsiVal, 20), 85).toFixed(1));
  }

  return points;
}

